  @doc "Number of entries per table — ADI's `SIZE_FULL_TABLE`."
  def size(), do: 77

  @doc """
  The table index whose absolute gain is closest to `db`, and the gain it gives.

  Indices are not dB. Asking for a gain in dB and getting back the index plus the
  gain actually achieved keeps the distinction visible at the call site.
  """
  @spec index_for_gain(0..2, number()) :: {:ok, {0..76, integer()}} | {:error, term()}
  def index_for_gain(band, db) do
    rows(band)
    |> Enum.with_index()
    |> Enum.min_by(fn {{_, _, _, g}, _i} -> abs(g - db) end)
    |> case do
      {{_, _, _, g}, i} -> {:ok, {i, g}}
      _ -> {:error, :empty_table}
    end
  end

