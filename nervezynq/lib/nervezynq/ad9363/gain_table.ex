  @moduledoc """
  ADI's RX gain tables and mixer Gm sub-table, transcribed from `ad9361.c`.

  The AD9363's receive gain is not a number you write — it is an **index into a
  table the host must first load into the chip**. Each of the 77 entries carries
  three bytes: the external/internal LNA and mixer gain word, the TIA and LPF
  word, and a DC-cal bit plus digital gain word. `ad9361_load_gt()` writes all 77
  through a small indexed port, and until it has, the gain index selects rows that
  were never programmed.

  **The table is band-dependent**, which is the part that matters. It sits inside
  ADI's own LO-set path (`ad9361_rfpll_set_rate` calls `ad9361_load_gt` at
  ad9361.c:7096), because retuning across a band boundary requires a different
  table. This project programmed the LO without it, and the symptom was a noise
  floor that tracked the LO across 700–3500 MHz with no peak in the WiFi band.

  Bands, from `ad9361_adi_gt_info[]` (ad9361.c:595), matched by
  `(start < freq) && (freq <= end)`:

      band 0  TBL_200_1300_MHZ    0 < f <= 1300 MHz    abs gain  -1 .. 73 dB
      band 1  TBL_1300_4000_MHZ   1300 < f <= 4000     abs gain  -3 .. 71 dB
      band 2  TBL_4000_6000_MHZ   4000 < f <= 6000     abs gain -10 .. 62 dB

  At 2412 MHz that is band 1. Note the AD9363 tops out at 3800 MHz, so band 2 is
  unreachable on this part.

  ## Generated, not typed — and the first attempt was wrong

  693 gain bytes plus 231 abs-gain values. Parsed from `ad9361.c` by script with
  invariants asserted at generation time: 3 blocks of 77 rows of 3 bytes, every
  byte in `0..255`, every abs-gain value inside `int8_t`, and each band's abs-gain
  column monotonically increasing.

  Those asserts earned their keep immediately. The first parse reported band 1's
  abs gain as `-3 .. 2300` — impossible for an `int8_t`. It had been reading the
  `/* 2300 MHz */` block comments as data. Stripping C comments before parsing
  fixed it, and the `int8_t` bound is what caught it. A hand transcription would
  have absorbed the same error silently, and a wrong abs-gain column produces a
  receiver whose commanded gain in dB is simply a lie.

  Only the full (non-split) tables are here. `split_gt` is a different table shape
  gated on `HAVE_SPLIT_GAIN_TABLE`, which is supplied by `app_config.h` and is not
  present in the no-OS tree at all — so its value cannot be determined from the
  source, and this project does not use it.
  """

